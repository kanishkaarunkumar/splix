-- SplitWise+ initial financial schema. Apply as the migration owner.
BEGIN;

CREATE EXTENSION IF NOT EXISTS pgcrypto;

CREATE TABLE users (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  email text NOT NULL,
  normalized_email text GENERATED ALWAYS AS (lower(btrim(email))) STORED,
  display_name text NOT NULL CHECK (length(btrim(display_name)) BETWEEN 1 AND 100),
  password_hash text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT users_normalized_email_uq UNIQUE (normalized_email)
);

CREATE TABLE groups (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  name text NOT NULL CHECK (length(btrim(name)) BETWEEN 1 AND 100),
  owner_id uuid NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  currency char(3) NOT NULL DEFAULT 'INR' CHECK (currency = 'INR'),
  timezone text NOT NULL DEFAULT 'Asia/Kolkata',
  version bigint NOT NULL DEFAULT 0 CHECK (version >= 0),
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE group_members (
  group_id uuid NOT NULL REFERENCES groups(id) ON DELETE RESTRICT,
  user_id uuid NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  joined_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (group_id, user_id)
);
CREATE INDEX group_members_user_group_idx ON group_members(user_id, group_id);

CREATE FUNCTION add_group_owner_membership() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  INSERT INTO group_members(group_id,user_id) VALUES(NEW.id,NEW.owner_id);
  RETURN NEW;
END;
$$;
CREATE TRIGGER groups_owner_membership_after_insert AFTER INSERT ON groups
FOR EACH ROW EXECUTE FUNCTION add_group_owner_membership();

CREATE TABLE categories (
  id smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL UNIQUE CHECK (length(btrim(name)) BETWEEN 1 AND 60)
);

CREATE TABLE financial_events (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  group_id uuid NOT NULL REFERENCES groups(id) ON DELETE RESTRICT,
  kind text NOT NULL CHECK (kind IN ('expense', 'settlement', 'reversal')),
  actor_id uuid NOT NULL,
  effective_date date NOT NULL,
  recorded_at timestamptz NOT NULL DEFAULT now(),
  reverses_event_id uuid UNIQUE,
  correction_of_event_id uuid,
  reason text,
  CONSTRAINT financial_events_id_group_uq UNIQUE (id, group_id),
  CONSTRAINT financial_events_actor_member_fk FOREIGN KEY (group_id, actor_id)
    REFERENCES group_members(group_id, user_id) ON DELETE RESTRICT,
  CONSTRAINT financial_events_reversal_fk FOREIGN KEY (reverses_event_id, group_id)
    REFERENCES financial_events(id, group_id) ON DELETE RESTRICT,
  CONSTRAINT financial_events_correction_fk FOREIGN KEY (correction_of_event_id, group_id)
    REFERENCES financial_events(id, group_id) ON DELETE RESTRICT,
  CONSTRAINT financial_events_reversal_shape CHECK (
    (kind = 'reversal' AND reverses_event_id IS NOT NULL AND reason IS NOT NULL AND length(btrim(reason)) > 0)
    OR (kind <> 'reversal' AND reverses_event_id IS NULL)
  ),
  CONSTRAINT financial_events_correction_shape CHECK (
    correction_of_event_id IS NULL OR kind = 'expense'
  )
);

CREATE TABLE expenses (
  event_id uuid PRIMARY KEY,
  group_id uuid NOT NULL,
  payer_id uuid NOT NULL,
  title text NOT NULL CHECK (length(btrim(title)) BETWEEN 1 AND 200),
  category_id smallint NOT NULL REFERENCES categories(id) ON DELETE RESTRICT,
  amount_paise bigint NOT NULL CHECK (amount_paise BETWEEN 1 AND 1000000000),
  split_method text NOT NULL CHECK (split_method IN ('equal', 'percentage', 'exact')),
  CONSTRAINT expenses_event_group_uq UNIQUE (event_id, group_id),
  CONSTRAINT expenses_event_fk FOREIGN KEY (event_id, group_id)
    REFERENCES financial_events(id, group_id) ON DELETE RESTRICT,
  CONSTRAINT expenses_payer_member_fk FOREIGN KEY (group_id, payer_id)
    REFERENCES group_members(group_id, user_id) ON DELETE RESTRICT
);

CREATE TABLE expense_shares (
  expense_event_id uuid NOT NULL,
  group_id uuid NOT NULL,
  user_id uuid NOT NULL,
  share_paise bigint NOT NULL CHECK (share_paise >= 0),
  percentage_bps integer CHECK (percentage_bps BETWEEN 0 AND 10000),
  PRIMARY KEY (expense_event_id, user_id),
  CONSTRAINT expense_shares_expense_fk FOREIGN KEY (expense_event_id, group_id)
    REFERENCES expenses(event_id, group_id) ON DELETE RESTRICT,
  CONSTRAINT expense_shares_member_fk FOREIGN KEY (group_id, user_id)
    REFERENCES group_members(group_id, user_id) ON DELETE RESTRICT
);

CREATE TABLE settlements (
  event_id uuid PRIMARY KEY,
  group_id uuid NOT NULL,
  from_user_id uuid NOT NULL,
  to_user_id uuid NOT NULL,
  amount_paise bigint NOT NULL CHECK (amount_paise BETWEEN 1 AND 1000000000),
  note text,
  CONSTRAINT settlements_distinct_users CHECK (from_user_id <> to_user_id),
  CONSTRAINT settlements_event_fk FOREIGN KEY (event_id, group_id)
    REFERENCES financial_events(id, group_id) ON DELETE RESTRICT,
  CONSTRAINT settlements_sender_member_fk FOREIGN KEY (group_id, from_user_id)
    REFERENCES group_members(group_id, user_id) ON DELETE RESTRICT,
  CONSTRAINT settlements_recipient_member_fk FOREIGN KEY (group_id, to_user_id)
    REFERENCES group_members(group_id, user_id) ON DELETE RESTRICT
);

CREATE TABLE ledger_entries (
  event_id uuid NOT NULL,
  group_id uuid NOT NULL,
  user_id uuid NOT NULL,
  delta_paise bigint NOT NULL,
  PRIMARY KEY (event_id, user_id),
  CONSTRAINT ledger_event_fk FOREIGN KEY (event_id, group_id)
    REFERENCES financial_events(id, group_id) ON DELETE RESTRICT,
  CONSTRAINT ledger_member_fk FOREIGN KEY (group_id, user_id)
    REFERENCES group_members(group_id, user_id) ON DELETE RESTRICT
);
CREATE INDEX ledger_entries_group_user_idx ON ledger_entries(group_id, user_id);
CREATE INDEX ledger_entries_group_event_idx ON ledger_entries(group_id, event_id);

CREATE TABLE idempotency_requests (
  actor_id uuid NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  group_id uuid NOT NULL REFERENCES groups(id) ON DELETE RESTRICT,
  request_key text NOT NULL CHECK (length(request_key) BETWEEN 1 AND 200),
  request_hash text NOT NULL,
  result_event_id uuid,
  response_json jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (actor_id, group_id, request_key),
  CONSTRAINT idempotency_result_group_fk FOREIGN KEY (result_event_id, group_id)
    REFERENCES financial_events(id, group_id) ON DELETE RESTRICT,
  CONSTRAINT idempotency_result_shape CHECK (
    (result_event_id IS NULL AND response_json IS NULL)
    OR (result_event_id IS NOT NULL AND response_json IS NOT NULL)
  )
);

CREATE INDEX financial_events_history_idx ON financial_events(group_id, recorded_at DESC, id DESC);
CREATE INDEX financial_events_month_idx ON financial_events(group_id, effective_date, id);
CREATE INDEX financial_events_correction_idx ON financial_events(group_id, correction_of_event_id)
  WHERE correction_of_event_id IS NOT NULL;

-- Derived balances are never stored: this view is an accounting projection of the immutable ledger.
CREATE VIEW member_balances AS
SELECT m.group_id, m.user_id, COALESCE(sum(l.delta_paise), 0)::bigint AS balance_paise
FROM group_members AS m
LEFT JOIN ledger_entries AS l USING (group_id, user_id)
GROUP BY m.group_id, m.user_id;

-- A deferred cross-row validator catches incomplete events, non-zero sums, incorrect source
-- postings, malformed reversal rows and incorrect share totals at transaction commit.
CREATE FUNCTION validate_financial_event(p_event_id uuid) RETURNS void
LANGUAGE plpgsql AS $$
DECLARE
  e financial_events%ROWTYPE;
  entry_count integer;
  entry_sum numeric;
  source_count integer;
  expected_count integer;
  share_sum numeric;
  expected_delta numeric;
BEGIN
  SELECT * INTO e FROM financial_events WHERE id = p_event_id;
  IF NOT FOUND THEN RETURN; END IF;

  SELECT count(*), COALESCE(sum(delta_paise), 0) INTO entry_count, entry_sum
  FROM ledger_entries WHERE event_id = p_event_id;
  IF entry_count = 0 OR entry_sum <> 0 THEN
    RAISE EXCEPTION 'event % must have ledger entries summing to zero', p_event_id USING ERRCODE = '23514';
  END IF;

  IF e.kind = 'expense' THEN
    IF NOT EXISTS (SELECT 1 FROM expenses WHERE event_id = p_event_id) THEN
      RAISE EXCEPTION 'expense event % requires expense details', p_event_id USING ERRCODE = '23514';
    END IF;
    IF EXISTS (SELECT 1 FROM settlements WHERE event_id = p_event_id) THEN
      RAISE EXCEPTION 'expense event % cannot have settlement details', p_event_id USING ERRCODE = '23514';
    END IF;
    SELECT count(*), COALESCE(sum(share_paise), 0),
           count(*) FILTER (WHERE percentage_bps IS NOT NULL),
           COALESCE(sum(percentage_bps), 0)
      INTO source_count, share_sum, expected_count, expected_delta
      FROM expense_shares WHERE expense_event_id = p_event_id;
    IF source_count = 0 OR share_sum <> (SELECT amount_paise FROM expenses WHERE event_id = p_event_id) THEN
      RAISE EXCEPTION 'expense % shares must sum to its amount', p_event_id USING ERRCODE = '23514';
    END IF;
    IF expected_count <> 0 AND (expected_count <> source_count OR expected_delta <> 10000) THEN
      RAISE EXCEPTION 'expense % percentages must be complete and sum to 10000 bps', p_event_id USING ERRCODE = '23514';
    END IF;
    IF EXISTS (
      SELECT 1 FROM (
        SELECT l.user_id,
               l.delta_paise - (CASE WHEN l.user_id = x.payer_id THEN x.amount_paise ELSE 0 END
                 - COALESCE(s.share_paise, 0)) AS mismatch
        FROM expenses x
        JOIN ledger_entries l ON l.event_id = x.event_id
        LEFT JOIN expense_shares s ON s.expense_event_id = x.event_id AND s.user_id = l.user_id
        WHERE x.event_id = p_event_id
      ) q WHERE mismatch <> 0
    ) OR EXISTS (
      SELECT 1 FROM expenses x JOIN expense_shares s ON s.expense_event_id = x.event_id
      LEFT JOIN ledger_entries l ON l.event_id = x.event_id AND l.user_id = s.user_id
      WHERE x.event_id = p_event_id AND l.event_id IS NULL AND s.share_paise <> 0
    ) OR EXISTS (
      SELECT 1 FROM expenses x LEFT JOIN ledger_entries l ON l.event_id = x.event_id AND l.user_id = x.payer_id
      WHERE x.event_id = p_event_id AND l.event_id IS NULL AND x.amount_paise <> 0
    ) THEN
      RAISE EXCEPTION 'expense % ledger does not match payer and shares', p_event_id USING ERRCODE = '23514';
    END IF;
  ELSIF e.kind = 'settlement' THEN
    IF NOT EXISTS (SELECT 1 FROM settlements WHERE event_id = p_event_id) THEN
      RAISE EXCEPTION 'settlement event % requires settlement details', p_event_id USING ERRCODE = '23514';
    END IF;
    IF EXISTS (SELECT 1 FROM expenses WHERE event_id = p_event_id) THEN
      RAISE EXCEPTION 'settlement event % cannot have expense details', p_event_id USING ERRCODE = '23514';
    END IF;
    IF EXISTS (
      SELECT 1 FROM settlements s
      WHERE s.event_id = p_event_id AND (
        (SELECT COALESCE(sum(delta_paise), 0) FROM ledger_entries WHERE event_id = p_event_id AND user_id = s.from_user_id) <> s.amount_paise
        OR (SELECT COALESCE(sum(delta_paise), 0) FROM ledger_entries WHERE event_id = p_event_id AND user_id = s.to_user_id) <> -s.amount_paise
        OR EXISTS (SELECT 1 FROM ledger_entries WHERE event_id = p_event_id AND user_id NOT IN (s.from_user_id, s.to_user_id))
      )
    ) THEN RAISE EXCEPTION 'settlement % ledger does not match endpoints', p_event_id USING ERRCODE = '23514'; END IF;
  ELSE
    IF EXISTS (SELECT 1 FROM expenses WHERE event_id = p_event_id)
       OR EXISTS (SELECT 1 FROM settlements WHERE event_id = p_event_id)
       OR EXISTS (SELECT 1 FROM financial_events source
                  WHERE source.id=e.reverses_event_id AND source.kind='reversal') THEN
      RAISE EXCEPTION 'reversal % must reference a non-reversal event and have no source subtype', p_event_id USING ERRCODE = '23514';
    END IF;
    IF EXISTS (
      SELECT 1 FROM ledger_entries reversal
      LEFT JOIN ledger_entries original ON original.event_id = e.reverses_event_id
       AND original.group_id = reversal.group_id AND original.user_id = reversal.user_id
      WHERE reversal.event_id = p_event_id AND reversal.delta_paise <> -COALESCE(original.delta_paise, 0)
    ) OR EXISTS (
      SELECT 1 FROM ledger_entries original
      LEFT JOIN ledger_entries reversal ON reversal.event_id = p_event_id
       AND reversal.group_id = original.group_id AND reversal.user_id = original.user_id
      WHERE original.event_id = e.reverses_event_id AND reversal.event_id IS NULL
    ) THEN RAISE EXCEPTION 'reversal % must exactly negate original ledger', p_event_id USING ERRCODE = '23514'; END IF;
  END IF;

  IF e.kind <> 'reversal' AND EXISTS (
    SELECT 1 FROM expenses WHERE event_id = p_event_id
  ) AND EXISTS (SELECT 1 FROM settlements WHERE event_id = p_event_id) THEN
    RAISE EXCEPTION 'event % cannot be both expense and settlement', p_event_id USING ERRCODE = '23514';
  END IF;
END;
$$;

-- Separate trigger functions avoid referencing columns absent on a given trigger record.
CREATE FUNCTION check_event_row_deferred() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN PERFORM validate_financial_event(NEW.id); RETURN NULL; END; $$;
CREATE FUNCTION check_child_event_deferred() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN PERFORM validate_financial_event(NEW.event_id); RETURN NULL; END; $$;
CREATE FUNCTION check_share_event_deferred() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN PERFORM validate_financial_event(NEW.expense_event_id); RETURN NULL; END; $$;
CREATE FUNCTION check_ledger_event_deferred() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN PERFORM validate_financial_event(NEW.event_id); RETURN NULL; END; $$;

CREATE CONSTRAINT TRIGGER financial_events_validate_ct
AFTER INSERT ON financial_events DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW EXECUTE FUNCTION check_event_row_deferred();
CREATE CONSTRAINT TRIGGER expenses_validate_ct
AFTER INSERT ON expenses DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW EXECUTE FUNCTION check_child_event_deferred();
CREATE CONSTRAINT TRIGGER settlements_validate_ct
AFTER INSERT ON settlements DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW EXECUTE FUNCTION check_child_event_deferred();
CREATE CONSTRAINT TRIGGER expense_shares_validate_ct
AFTER INSERT ON expense_shares DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW EXECUTE FUNCTION check_share_event_deferred();
CREATE CONSTRAINT TRIGGER ledger_entries_validate_ct
AFTER INSERT ON ledger_entries DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW EXECUTE FUNCTION check_ledger_event_deferred();

-- Controlled posting entry points. The service still validates request shape/split allocation,
-- while PostgreSQL rechecks membership, totals, settlement limits, atomicity and group ordering.
CREATE FUNCTION post_expense(
  p_group_id uuid, p_actor_id uuid, p_payer_id uuid, p_effective_date date, p_title text,
  p_category_id smallint, p_amount_paise bigint, p_split_method text, p_shares jsonb
) RETURNS uuid LANGUAGE plpgsql SECURITY DEFINER
SET search_path = pg_catalog, public AS $$
DECLARE
  v_event_id uuid := gen_random_uuid();
  v_share_total numeric;
  v_share_count integer;
  v_share_user uuid;
  v_share bigint;
  v_percent integer;
  v_percent_count integer;
  v_percent_total integer;
BEGIN
  PERFORM 1 FROM groups WHERE id = p_group_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'group not found' USING ERRCODE = '23503'; END IF;
  IF NOT EXISTS (SELECT 1 FROM group_members WHERE group_id=p_group_id AND user_id=p_actor_id) THEN
    RAISE EXCEPTION 'actor is not a group member' USING ERRCODE = '42501';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM group_members WHERE group_id=p_group_id AND user_id=p_payer_id) THEN
    RAISE EXCEPTION 'payer is not a group member' USING ERRCODE = '23503';
  END IF;
  IF p_amount_paise NOT BETWEEN 1 AND 1000000000 OR p_split_method NOT IN ('equal','percentage','exact') THEN
    RAISE EXCEPTION 'invalid expense amount or split method' USING ERRCODE = '22023';
  END IF;
  IF p_shares IS NULL OR jsonb_typeof(p_shares->'shares') IS DISTINCT FROM 'array'
     OR jsonb_array_length(p_shares->'shares') = 0 THEN
    RAISE EXCEPTION 'expense needs at least one participant' USING ERRCODE = '22023';
  END IF;
  SELECT count(*), sum(share_paise), count(percentage_bps), COALESCE(sum(percentage_bps),0)
    INTO v_share_count, v_share_total, v_percent_count, v_percent_total
  FROM jsonb_to_recordset(p_shares->'shares') AS s(user_id uuid, share_paise bigint, percentage_bps integer);
  IF v_share_count <> jsonb_array_length(p_shares->'shares') OR v_share_total <> p_amount_paise THEN
    RAISE EXCEPTION 'shares must be unique and sum exactly to expense amount' USING ERRCODE = '23514';
  END IF;
  IF p_split_method = 'percentage' AND (v_percent_count <> v_share_count OR v_percent_total <> 10000) THEN
    RAISE EXCEPTION 'percentage split must provide weights totaling 10000 bps' USING ERRCODE = '23514';
  ELSIF p_split_method <> 'percentage' AND v_percent_count <> 0 THEN
    RAISE EXCEPTION 'percentage weights only apply to percentage splits' USING ERRCODE = '23514';
  END IF;

  INSERT INTO financial_events(id, group_id, kind, actor_id, effective_date)
    VALUES (v_event_id,p_group_id,'expense',p_actor_id,p_effective_date);
  INSERT INTO expenses(event_id,group_id,payer_id,title,category_id,amount_paise,split_method)
    VALUES (v_event_id,p_group_id,p_payer_id,p_title,p_category_id,p_amount_paise,p_split_method);
  INSERT INTO expense_shares(expense_event_id,group_id,user_id,share_paise,percentage_bps)
    SELECT v_event_id,p_group_id,s.user_id,s.share_paise,s.percentage_bps
    FROM jsonb_to_recordset(p_shares->'shares') AS s(user_id uuid, share_paise bigint, percentage_bps integer);
  IF EXISTS (SELECT 1 FROM expense_shares WHERE expense_event_id=v_event_id GROUP BY user_id HAVING count(*) > 1) THEN
    RAISE EXCEPTION 'duplicate participant' USING ERRCODE = '23505';
  END IF;
  INSERT INTO ledger_entries(event_id,group_id,user_id,delta_paise)
    SELECT v_event_id,p_group_id,user_id,sum(delta)::bigint
    FROM (
      SELECT p_payer_id AS user_id,p_amount_paise::numeric AS delta
      UNION ALL
      SELECT s.user_id,-s.share_paise::numeric FROM expense_shares s WHERE s.expense_event_id=v_event_id
    ) postings GROUP BY user_id;
  UPDATE groups SET version=version+1 WHERE id=p_group_id;
  RETURN v_event_id;
END;
$$;

CREATE FUNCTION post_settlement(
  p_group_id uuid, p_actor_id uuid, p_effective_date date,
  p_from_user_id uuid, p_to_user_id uuid, p_amount_paise bigint, p_note text DEFAULT NULL
) RETURNS uuid LANGUAGE plpgsql SECURITY DEFINER
SET search_path = pg_catalog, public AS $$
DECLARE
  v_event_id uuid := gen_random_uuid();
  v_from_balance numeric;
  v_to_balance numeric;
BEGIN
  PERFORM 1 FROM groups WHERE id=p_group_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'group not found' USING ERRCODE = '23503'; END IF;
  IF NOT EXISTS (SELECT 1 FROM group_members WHERE group_id=p_group_id AND user_id=p_actor_id) THEN
    RAISE EXCEPTION 'actor is not a group member' USING ERRCODE = '42501';
  END IF;
  IF p_from_user_id=p_to_user_id OR p_amount_paise NOT BETWEEN 1 AND 1000000000 THEN
    RAISE EXCEPTION 'invalid settlement endpoints or amount' USING ERRCODE = '22023';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM group_members WHERE group_id=p_group_id AND user_id=p_from_user_id)
     OR NOT EXISTS (SELECT 1 FROM group_members WHERE group_id=p_group_id AND user_id=p_to_user_id) THEN
    RAISE EXCEPTION 'settlement endpoints must be group members' USING ERRCODE = '23503';
  END IF;
  IF p_actor_id <> p_from_user_id AND NOT EXISTS (
    SELECT 1 FROM groups WHERE id=p_group_id AND owner_id=p_actor_id
  ) THEN RAISE EXCEPTION 'only sender or group owner may record settlement' USING ERRCODE = '42501'; END IF;
  SELECT COALESCE(sum(delta_paise),0) INTO v_from_balance FROM ledger_entries WHERE group_id=p_group_id AND user_id=p_from_user_id;
  SELECT COALESCE(sum(delta_paise),0) INTO v_to_balance FROM ledger_entries WHERE group_id=p_group_id AND user_id=p_to_user_id;
  IF v_from_balance >= 0 OR v_to_balance <= 0 OR p_amount_paise > LEAST(-v_from_balance,v_to_balance) THEN
    RAISE EXCEPTION 'settlement exceeds current debt or credit' USING ERRCODE = '23514';
  END IF;
  INSERT INTO financial_events(id,group_id,kind,actor_id,effective_date)
    VALUES(v_event_id,p_group_id,'settlement',p_actor_id,p_effective_date);
  INSERT INTO settlements(event_id,group_id,from_user_id,to_user_id,amount_paise,note)
    VALUES(v_event_id,p_group_id,p_from_user_id,p_to_user_id,p_amount_paise,p_note);
  INSERT INTO ledger_entries(event_id,group_id,user_id,delta_paise) VALUES
    (v_event_id,p_group_id,p_from_user_id,p_amount_paise),
    (v_event_id,p_group_id,p_to_user_id,-p_amount_paise);
  UPDATE groups SET version=version+1 WHERE id=p_group_id;
  RETURN v_event_id;
END;
$$;

CREATE FUNCTION reverse_financial_event(
  p_group_id uuid, p_event_id uuid, p_actor_id uuid, p_reason text
) RETURNS uuid LANGUAGE plpgsql SECURITY DEFINER
SET search_path = pg_catalog, public AS $$
DECLARE
  v_original financial_events%ROWTYPE;
  v_event_id uuid := gen_random_uuid();
BEGIN
  PERFORM 1 FROM groups WHERE id=p_group_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'group not found' USING ERRCODE = '23503'; END IF;
  SELECT * INTO v_original FROM financial_events WHERE id=p_event_id AND group_id=p_group_id;
  IF NOT FOUND OR v_original.kind='reversal' THEN RAISE EXCEPTION 'event cannot be reversed' USING ERRCODE = '22023'; END IF;
  IF NOT EXISTS (SELECT 1 FROM group_members WHERE group_id=p_group_id AND user_id=p_actor_id) THEN
    RAISE EXCEPTION 'actor is not a group member' USING ERRCODE = '42501';
  END IF;
  IF p_actor_id <> v_original.actor_id AND NOT EXISTS (
    SELECT 1 FROM groups WHERE id=p_group_id AND owner_id=p_actor_id
  ) THEN RAISE EXCEPTION 'only original actor or group owner may reverse' USING ERRCODE = '42501'; END IF;
  IF EXISTS (SELECT 1 FROM financial_events WHERE reverses_event_id=p_event_id) THEN
    RAISE EXCEPTION 'event already reversed' USING ERRCODE = '23505';
  END IF;
  IF length(btrim(p_reason))=0 THEN RAISE EXCEPTION 'reason required' USING ERRCODE = '22023'; END IF;
  INSERT INTO financial_events(id,group_id,kind,actor_id,effective_date,reverses_event_id,reason)
    VALUES(v_event_id,p_group_id,'reversal',p_actor_id,v_original.effective_date,p_event_id,p_reason);
  INSERT INTO ledger_entries(event_id,group_id,user_id,delta_paise)
    SELECT v_event_id,p_group_id,user_id,-delta_paise FROM ledger_entries WHERE event_id=p_event_id;
  UPDATE groups SET version=version+1 WHERE id=p_group_id;
  RETURN v_event_id;
END;
$$;

CREATE FUNCTION reject_financial_mutation() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN RAISE EXCEPTION 'financial history is append-only' USING ERRCODE = '55000'; END; $$;
CREATE TRIGGER financial_events_immutable BEFORE UPDATE OR DELETE ON financial_events
FOR EACH ROW EXECUTE FUNCTION reject_financial_mutation();
CREATE TRIGGER expenses_immutable BEFORE UPDATE OR DELETE ON expenses
FOR EACH ROW EXECUTE FUNCTION reject_financial_mutation();
CREATE TRIGGER expense_shares_immutable BEFORE UPDATE OR DELETE ON expense_shares
FOR EACH ROW EXECUTE FUNCTION reject_financial_mutation();
